"""Markdown index generation (roadmap V8).

Indexes are plain Markdown pages named ``_index.md``.  They are regenerated
from the entries, never edited by hand, and carry a marker so the checker and
humans can tell them apart from real content.

Four levels are produced:

* ``content/_index.md`` — the portfolio entry point, listing domains;
* ``content/<domain>/_index.md`` — subdomains of one domain;
* ``content/<domain>/<subdomain>/_index.md`` — content types of one subdomain;
* ``content/<domain>/<subdomain>/<type>/_index.md`` — the entries themselves.
"""

from __future__ import annotations

from pathlib import Path

from .config import Config
from .frontmatter import render
from .models import CONTENT_FOLDERS, INDEX_FILENAME, TYPE_METADATA_FIELDS, Entry
from .store import iter_entries

#: Marker written in every generated index.  Its presence tells a human (and
#: the tests) that the file can be regenerated without losing anything.
GENERATED_MARKER = "<!-- generated by portfolio-manager: do not edit by hand -->"

#: Link style accepted by :func:`generate_indexes`.
LINK_STYLES = ("relative", "hugo")


def _link_for(entry: Entry, style: str) -> str:
    """Return the Markdown link target for ``entry``.

    Relative links are computed from the type folder that contains the index,
    so they work on GitHub and in Obsidian without a static site generator.
    """
    if style == "hugo":
        # Hugo pretty URLs: /domain/subdomain/type/slug/
        stem = entry.path.stem
        slug = entry.path.parent.name if stem == "index" else stem
        return (
            f"/{entry.domain}/{entry.subdomain}/"
            f"{CONTENT_FOLDERS.get(entry.type, entry.type)}/{slug}/"
        )
    type_folder = entry.path.parent.parent if entry.path.name == "index.md" else entry.path.parent
    return entry.path.relative_to(type_folder).as_posix()


def _entry_line(entry: Entry, style: str) -> str:
    """Render one bullet for an entry list."""
    title = entry.title or entry.path.stem
    date = f" — {entry.date}" if entry.date else ""
    draft = " *(draft)*" if entry.is_draft else ""
    tags = f" `{'`, `'.join(entry.tags)}`" if entry.tags else ""
    return f"- [{title}]({_link_for(entry, style)}){date}{draft}{tags}"


def _page(title: str, intro: str, lines: list[str], *, date: str) -> str:
    """Assemble a generated page with minimal, valid front matter."""
    metadata = {
        "title": title,
        "type": "index",
        "date": date,
        "status": "published",
        "draft": False,
        "tags": [],
    }
    body = f"{GENERATED_MARKER}\n\n# {title}\n\n{intro}\n"
    if lines:
        body += "\n" + "\n".join(lines) + "\n"
    return render(metadata, body, normalize_separator=True)


def generate_indexes(
    config: Config,
    *,
    include_drafts: bool = True,
    link_style: str = "relative",
    dry_run: bool = False,
) -> list[Path]:
    """Regenerate every ``_index.md`` file of the portfolio.

    Args:
        config: Resolved configuration.
        include_drafts: List drafts in the generated pages (they are marked).
        link_style: ``relative`` (GitHub and Obsidian friendly) or ``hugo``
            (absolute pretty URLs).
        dry_run: Compute the files without writing them.

    Returns:
        The list of index files that were (or would be) written.
    """
    if link_style not in LINK_STYLES:
        raise ValueError(f"unknown link style: {link_style}")

    entries = iter_entries(config.portfolio_root)
    today = _today()
    written: list[Path] = []

    # Group every entry by (domain, subdomain, type).  Drafts are kept in the
    # structure so an index is regenerated (and emptied) instead of going stale
    # when drafts are excluded.
    groups: dict[tuple[str, str, str], list[Entry]] = {}
    for entry in entries:
        groups.setdefault((entry.domain, entry.subdomain, entry.type), []).append(entry)

    root = config.portfolio_root
    domains: dict[str, dict[str, set[str]]] = {}
    for domain, subdomain, content_type in groups:
        domains.setdefault(domain, {}).setdefault(subdomain, set()).add(content_type)

    def visible(items: list[Entry]) -> list[Entry]:
        """Entries listed in the generated pages."""
        return items if include_drafts else [item for item in items if not item.is_draft]

    # 1. Root index.
    domain_lines = [
        f"- [{domain.title()}]({domain}/_index.md) — "
        f"{sum(len(items) for items in subdomains.values())} subdomain(s)"
        for domain, subdomains in sorted(domains.items())
    ]
    written.append(
        _write(
            root / "content" / INDEX_FILENAME,
            _page(
                "Portfolio",
                "Technical portfolio: projects, labs, publications and reading notes.",
                domain_lines,
                date=today,
            ),
            dry_run=dry_run,
        )
    )

    # 2. Domain and subdomain indexes.
    for domain, subdomains in sorted(domains.items()):
        sub_lines = [
            f"- [{subdomain.title()}]({subdomain}/_index.md)" for subdomain in sorted(subdomains)
        ]
        written.append(
            _write(
                root / "content" / domain / INDEX_FILENAME,
                _page(
                    domain.title(),
                    f"Content published in the *{domain}* domain.",
                    sub_lines,
                    date=today,
                ),
                dry_run=dry_run,
            )
        )

        for subdomain, content_types in sorted(subdomains.items()):
            type_lines = [
                f"- [{content_type.title()}]({CONTENT_FOLDERS[content_type]}/_index.md) "
                f"— {len(visible(groups[(domain, subdomain, content_type)]))} item(s)"
                for content_type in sorted(content_types, key=_type_order)
            ]
            written.append(
                _write(
                    root / "content" / domain / subdomain / INDEX_FILENAME,
                    _page(
                        subdomain.replace("-", " ").title(),
                        f"{domain} / {subdomain}.",
                        type_lines,
                        date=today,
                    ),
                    dry_run=dry_run,
                )
            )

            # 3. Type index: the actual entry list.
            for content_type in sorted(content_types, key=_type_order):
                folder = CONTENT_FOLDERS[content_type]
                items = sorted(
                    visible(groups[(domain, subdomain, content_type)]),
                    key=lambda item: (item.date, item.title.lower()),
                    reverse=True,
                )
                entry_lines = [_entry_line(item, link_style) for item in items]
                written.append(
                    _write(
                        root / "content" / domain / subdomain / folder / INDEX_FILENAME,
                        _page(
                            f"{content_type.title()} — {subdomain.replace('-', ' ').title()}",
                            f"{len(entry_lines)} entry(ies), most recent first.",
                            entry_lines,
                            date=today,
                        ),
                        dry_run=dry_run,
                    )
                )

    return sorted(written)


def _type_order(content_type: str) -> int:
    """Stable display order for content types."""
    order = {name: index for index, name in enumerate(TYPE_METADATA_FIELDS)}
    return order.get(content_type, len(order))


def _today() -> str:
    """Today's ISO date (kept in a helper for easy testing)."""
    import datetime as _dt

    return _dt.date.today().isoformat()


def _write(path: Path, content: str, *, dry_run: bool) -> Path:
    """Write an index file unless ``dry_run`` is set."""
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return path
